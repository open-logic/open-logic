    function tableIndex (Name : string) return natural is
    begin

        if Name = "log2_f10" then
            return 0;

        elsif Name = "log2_f14" then
            return 1;

        elsif Name = "log2_f18" then
            return 2;

        elsif Name = "log2_f20" then
            return 3;

        -- Excluded from coverage because this line can't be reached with valid table names
        -- coverage off
        else
            report "olo_fix_private_lin_approx_log2_pkg: no table named '" & Name & "'. Available tables: " &
                   "log2_f10, log2_f14, log2_f18, log2_f20"
                severity failure;
            return 0;
        end if;
        -- coverage on
    end function;

