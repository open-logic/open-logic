    -- *** Name Lookup ***
    function tableIndex (Name : string) return natural is
    begin

        if Name = "inv_f10" then
            return 0;
        end if;

        if Name = "inv_f14" then
            return 1;
        end if;

        if Name = "inv_f18" then
            return 2;
        end if;

        if Name = "inv_f20" then
            return 3;
        end if;

        report "olo_fix_private_lin_approx_inv_pkg: no table named '" & Name & "'. Available tables: " &
               "inv_f10, inv_f14, inv_f18, inv_f20"
            severity failure;
        return 0;
    end function;

    -- *** Public Functions ***
    function getTable (Name : string) return LinApproxTable_t is
    begin

        case tableIndex(Name) is
            when 0 => return Table0_c;
            when 1 => return Table1_c;
            when 2 => return Table2_c;
            when 3 => return Table3_c;
            when others => return Table0_c;
        end case;

    end function;

    function getTableSize (Name : string) return positive is
    begin
        return Points_c(tableIndex(Name));
    end function;

    function getOffsetFmt (Name : string) return string is
    begin
        return to_string(OffsFmts_c(tableIndex(Name)));
    end function;

    function getGradientFmt (Name : string) return string is
