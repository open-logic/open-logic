package olo_fix_private_lin_approx_inv_pkg is

    -- Width one table entry is padded to. The entries of all tables share the same width so they
    -- can be stored in one array type. The padding is meant to be sliced away by the entity, hence
    -- it does not cost any memory.
    constant LinApproxEntryWidth_c : positive := 36;

    -- Types
    subtype LinApproxEntry_t is std_logic_vector(LinApproxEntryWidth_c - 1 downto 0);
    type LinApproxTable_t is array (natural range <>) of LinApproxEntry_t;

    -- Table content of the approximation with the given name. Each entry contains the gradient
    -- (MSBs) and the offset (LSBs), zero padded to LinApproxEntryWidth_c.
    function getTable (Name : string) return LinApproxTable_t;

    -- Number of points (segments) of the table of the approximation with the given name
    function getTableSize (Name : string) return positive;

    -- Number formats the table entries of the approximation with the given name are coded in
    function getOffsetFmt (Name : string) return string;
    function getGradientFmt (Name : string) return string;

end package;

