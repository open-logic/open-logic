    function tableIndex (Name : string) return natural is
    begin

        if Name = "inv_f10" then
            return 0;

        elsif Name = "inv_f14" then
            return 1;

        elsif Name = "inv_f18" then
            return 2;

        elsif Name = "inv_f20" then
            return 3;

