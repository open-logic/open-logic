-- Description
---------------------------------------------------------------------------------------------------
-- Tables for linear function approximations (see olo_fix_lin_approx_calc). The package contains one
-- table per approximation, so an entity can select between them at elaboration time.
--
-- DO NOT EDIT MANUALLY - this file is generated by the Python model olo_fix_lin_approx. The table
-- content is generated in Python (and not calculated in VHDL) because the accuracy of
-- ieee.math_real is implementation defined and would therefore differ between tools.
--
-- Documentation:
-- https://github.com/open-logic/open-logic/blob/main/doc/fix/olo_fix_lin_approx.md

